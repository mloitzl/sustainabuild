import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { userTypeSdl, viewerQueryField } from '../src/lib/graphql/viewer-sdl.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const coreSchemaSource = path.resolve(__dirname, '../../core-api/src/graphql/schema.ts');
const relaySchemaTarget = path.resolve(__dirname, '../schema.graphql');
const coreSdlGeneratedTarget = path.resolve(__dirname, '../src/lib/graphql/core-sdl.generated.ts');

const source = fs.readFileSync(coreSchemaSource, 'utf8');
const match = source.match(/export const typeDefs = \/\* GraphQL \*\/ `([\s\S]*?)`;\s*$/m);

if (!match || !match[1]) {
  throw new Error(`Unable to extract GraphQL SDL from ${coreSchemaSource}`);
}

const coreSdl = match[1].trim();

// 1. Relay schema: Core SDL with `viewer` spliced into the Query block + the
//    appended User type, so relay-compiler validates `viewer` queries against the
//    same shape the gateway serves. The field MUST live inside `type Query`
//    (not `extend type Query`): relay-compiler treats extend-introduced fields as
//    client-only extensions and strips them from the server query text.
const queryBlock = /type Query \{\n/;
if (!queryBlock.test(coreSdl)) {
  throw new Error('Unable to locate "type Query {" block in Core SDL to splice viewer field');
}
const withViewer = coreSdl.replace(queryBlock, (m) => `${m}${viewerQueryField}\n`);
const stitchedSdl = `${withViewer}\n\n${userTypeSdl.trim()}\n`;
fs.writeFileSync(relaySchemaTarget, stitchedSdl, 'utf8');
console.log(`[relay:schema] Wrote ${relaySchemaTarget}`);

// 2. Generated TS const: the gateway builds the remote (Core API) subschema from
//    this SDL via buildSchema(), so it never re-extracts and cannot drift from
//    what relay-compiler sees. Core SDL contains no backticks or ${, but escape
//    defensively in case that changes upstream.
const escaped = coreSdl.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const generated = `// AUTO-GENERATED by scripts/generate-relay-schema.mjs — do not edit by hand.
// Source: apps/core-api/src/graphql/schema.ts (extracted typeDefs).
export const coreSdl = /* GraphQL */ \`${escaped}\`;
`;
fs.writeFileSync(coreSdlGeneratedTarget, generated, 'utf8');
console.log(`[relay:schema] Wrote ${coreSdlGeneratedTarget}`);
